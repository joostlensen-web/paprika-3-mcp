// updateResources keeps the recipe cache in sync and exposes new or changed recipes as MCP resources
func (s *Server) updateResources() {
	s.addResources()

	ticker := time.NewTicker(resourceRefreshInterval)
	for range ticker.C {
		s.addResources()
	}
}

func (s *Server) addResources() {
	s.logger.Info("Updating recipe resources")
	ctx, cancel := context.WithTimeout(context.Background(), readTimeout)
	defer cancel()

	changed, err := s.cache.refresh(ctx, 0)
	if err != nil {
		s.logger.Error("failed to refresh paprika recipes", "err", err)
	}

	for _, recipe := range changed {
		s.addRecipeResource(recipe)
	}
}

func (s *Server) addRecipeResource(recipe paprika.Recipe) {
	resourceContents := mcp.TextResourceContents{
		URI:      fmt.Sprintf("paprika://recipes/%s", recipe.UID),
		MIMEType: "text/markdown",
		Text:     recipe.ToMarkdown(),
	}

	s.server.AddResource(mcp.NewResource(fmt.Sprintf("paprika://recipes/%s", recipe.UID), recipe.Name, mcp.WithResourceDescription(recipe.ResourceDescription()), mcp.WithMIMEType("text/markdown")), func(ctx context.Context, request mcp.ReadResourceRequest) ([]mcp.ResourceContents, error) {
		return []mcp.ResourceContents{resourceContents}, nil
	})
}

// stringArg returns an optional string argument; missing or non-string values become ""
func stringArg(args map[string]interface{}, key string) string {
	v, _ := args[key].(string)
	return v
}

// stringSliceArg returns an optional list argument. Clients sometimes send a comma-separated string instead of an array.
func stringSliceArg(args map[string]interface{}, key string) []string {
	var out []string
	switch v := args[key].(type) {
	case []interface{}:
		for _, item := range v {
			if str, ok := item.(string); ok && strings.TrimSpace(str) != "" {
				out = append(out, strings.TrimSpace(str))
			}
		}
	case string:
		for _, str := range strings.Split(v, ",") {
			if strings.TrimSpace(str) != "" {
				out = append(out, strings.TrimSpace(str))
			}
		}
	}
	return out
}

func (s *Server) createRecipe(ctx context.Context, req mcp.CallToolRequest) (*mcp.CallToolResult, error) {
	start := time.Now()
	name, ok := req.Params.Arguments["name"].(string)
	if !ok || len(name) == 0 {
		return nil, errors.New("name is required")
	}
	ingredients, ok := req.Params.Arguments["ingredients"].(string)
	if !ok || len(ingredients) == 0 {
		return nil, errors.New("ingredients are required")
	}
	directions, ok := req.Params.Arguments["directions"].(string)
	if !ok || len(directions) == 0 {
		return nil, errors.New("directions are required")
	}
	args := req.Params.Arguments

	// Categories are resolved before anything is saved, so an unknown category never leaves a half-created recipe
	readCtx, cancel := context.WithTimeout(ctx, readTimeout)
	defer cancel()
	if err := s.cache.ensureFresh(readCtx, cacheMaxAge); err != nil {
		return nil, err
	}
	_, categories := s.cache.snapshot()
	categoryUIDs, err := newCategoryIndex(categories).resolveCategories(stringSliceArg(args, "categories"))
	if err != nil {
		return mcp.NewToolResultError(err.Error()), nil
	}

	ctx, cancel = context.WithTimeout(ctx, writeTimeout)
	defer cancel()
	recipe, err := s.paprika3.SaveRecipe(ctx, paprika.Recipe{
		Name:        name,
		Ingredients: ingredients,
		Directions:  directions,
		Description: stringArg(args, "description"),
		Servings:    stringArg(args, "servings"),
		PrepTime:    stringArg(args, "prep_time"),
		CookTime:    stringArg(args, "cook_time"),
		Notes:       stringArg(args, "notes"),
		Difficulty:  stringArg(args, "difficulty"),
		Source:      stringArg(args, "source"),
		SourceURL:   stringArg(args, "source_url"),
		Categories:  categoryUIDs,
	})
	if err != nil {
		return nil, err
	}
	s.cache.put(*recipe)

	duration := time.Since(start)
	s.logger.Info("Created recipe", "name", recipe.Name, "uid", recipe.UID, "duration", duration)

	return s.recipeResult(*recipe, categories), nil
}

func (s *Server) updateRecipe(ctx context.Context, req mcp.CallToolRequest) (*mcp.CallToolResult, error) {
	start := time.Now()
	args := req.Params.Arguments
	uid, ok := args["uid"].(string)
	if !ok || len(uid) == 0 {
		return nil, errors.New("uid is required")
	}

	readCtx, cancel := context.WithTimeout(ctx, readTimeout)
	defer cancel()
	if err := s.cache.ensureFresh(readCtx, cacheMaxAge); err != nil {
		return nil, err
	}
	_, categories := s.cache.snapshot()

	// Start from the stored recipe so fields the caller doesn't pass (categories, photo, rating, ...) are kept
	ctx, cancel = context.WithTimeout(ctx, writeTimeout)
	defer cancel()
	recipe, err := s.paprika3.GetRecipe(ctx, uid)
	if err != nil {
		return nil, err
	}

	fields := map[string]*string{
		"name":        &recipe.Name,
		"ingredients": &recipe.Ingredients,
		"directions":  &recipe.Directions,
		"description": &recipe.Description,
		"notes":       &recipe.Notes,
		"servings":    &recipe.Servings,
		"prep_time":   &recipe.PrepTime,
		"cook_time":   &recipe.CookTime,
		"difficulty":  &recipe.Difficulty,
		"source":      &recipe.Source,
		"source_url":  &recipe.SourceURL,
	}
	for key, field := range fields {
		if v, ok := args[key].(string); ok {
			*field = v
		}
	}
	if recipe.Name == "" {
		return mcp.NewToolResultError("name cannot be empty"), nil
	}
	if _, ok := args["categories"]; ok {
		categoryUIDs, err := newCategoryIndex(categories).resolveCategories(stringSliceArg(args, "categories"))
		if err != nil {
			return mcp.NewToolResultError(err.Error()), nil
		}
		recipe.Categories = categoryUIDs
	}

	recipe, err = s.paprika3.SaveRecipe(ctx, *recipe)
	if err != nil {
		return nil, err
	}
	s.cache.put(*recipe)

	duration := time.Since(start)
	s.logger.Info("Updated recipe", "name", recipe.Name, "uid", recipe.UID, "duration", duration)

	return s.recipeResult(*recipe, categories), nil
}

// recipeResult returns a saved recipe as markdown, with its uid and category names
func (s *Server) recipeResult(recipe paprika.Recipe, categories []paprika.Category) *mcp.CallToolResult {
	return mcp.NewToolResultResource(recipe.Name, mcp.TextResourceContents{
		URI:      fmt.Sprintf("paprika://recipes/%s", recipe.UID),
		MIMEType: "text/markdown",
		Text:     recipeMarkdown(recipe, newCategoryIndex(categories)),
	})
}

// recipeMarkdown renders a recipe with the uid and category names, which Recipe.ToMarkdown leaves out
func recipeMarkdown(recipe paprika.Recipe, ix *categoryIndex) string {
	var sb strings.Builder
	sb.WriteString(recipe.ToMarkdown())
	sb.WriteString("## Paprika\n")
	if names := ix.names(recipe.Categories); len(names) > 0 {
		sb.WriteString(fmt.Sprintf("- **Categories:** %s\n", strings.Join(names, ", ")))
	} else {
		sb.WriteString("- **Categories:** none\n")
	}
	if recipe.Source != "" {
		sb.WriteString(fmt.Sprintf("- **Source:** %s\n", recipe.Source))
	}
	if recipe.SourceURL != "" {
		sb.WriteString(fmt.Sprintf("- **Source URL:** %s\n", recipe.SourceURL))
	}
	sb.WriteString(fmt.Sprintf("- **UID:** %s\n", recipe.UID))
	return sb.String()
}
