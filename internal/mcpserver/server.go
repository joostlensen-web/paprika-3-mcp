type NewServerOptions struct {
	Version  string
	Username string
	Password string
	Paprika  *paprika.Client
	Logger   *slog.Logger
	// CachePath is where the recipe cache is stored between runs; empty keeps it in memory only
	CachePath string
}

func NewServer(opts NewServerOptions) (*Server, error) {
	paprika3, err := paprika.NewClient(opts.Username, opts.Password, opts.Version, opts.Logger)
	if err != nil {
		return nil, err
	}

	return newServer(paprika3, opts.Version, opts.Logger, opts.CachePath), nil
}

func newServer(client paprikaClient, version string, logger *slog.Logger, cachePath string) *Server {
	s := server.NewMCPServer("paprika-3-mcp", version, server.WithResourceCapabilities(false, false))
	return &Server{
		paprika3: client,
		cache:    newRecipeCache(client, logger, cachePath),
		server:   s,
		logger:   logger,
	}
}

type Server struct {
	paprika3 paprikaClient
	cache    *recipeCache
	logger   *slog.Logger
	server   *server.MCPServer
}

const (
	// resourceRefreshInterval is how often the background loop syncs the recipe cache
	resourceRefreshInterval = 5 * time.Minute
	// cacheMaxAge is how stale the cache may be when a tool reads it; a refresh only fetches changed recipes
	cacheMaxAge = 1 * time.Minute
	// readTimeout allows for the first full load of the recipe cache
	readTimeout  = 3 * time.Minute
	writeTimeout = 30 * time.Second
)

func (s *Server) Start() {
	go s.updateResources()

	s.server.AddTools(s.tools()...)

	if err := server.ServeStdio(s.server); err != nil {
		s.logger.Error("Server error", "err", err)
	}
}

